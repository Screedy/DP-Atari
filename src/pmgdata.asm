    .BYTE %00111100     ; line 3  ..####..
    .BYTE %00000000     ; line 4  ........
    .BYTE %10000001     ; line 5  #......#
    .BYTE %00000000     ; line 6  ........
    .BYTE %00000000     ; line 7  ........
